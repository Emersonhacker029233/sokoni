<?php

namespace App\Http\Requests\Delivery;

use Illuminate\Foundation\Http\FormRequest;
use Illuminate\Validation\Rule;

/**
 * POST /delivery/orders/{order}/pay. The amount is never part of the
 * request: the server charges the fee frozen on the job.
 */
class PayDeliveryRequest extends FormRequest
{
    public function authorize(): bool
    {
        return true;
    }

    public function rules(): array
    {
        return [
            'channel' => ['required', Rule::in((array) config('payments.channels'))],
            // The mobile-money number that gets the prompt, E.164 (+2557XXXXXXXX / +2556XXXXXXXX).
            'msisdn' => ['required', 'string', 'regex:/^\+255[67]\d{8}$/'],
            // One per attempt, generated by the app; a retry of the same tap reuses it.
            'idempotency_key' => ['required', 'string', 'min:8', 'max:100', 'regex:/^[A-Za-z0-9_-]+$/'],
        ];
    }
}
